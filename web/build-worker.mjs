// Builds web/dist/worker.js: one self-contained Cloudflare Worker with the
// function and the page inlined, so it can be pasted into the dashboard with no
// CLI and no Git connection.
//
//   node build-worker.mjs
//
// The function stays the single source of truth; this only rewrites its module
// syntax into plain declarations and appends the static files.

import path from "node:path";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => readFile(path.join(here, p), "utf8");

let fn = await read("netlify/functions/ytm.js");
fn = fn.replace("export default async (req) => {", "async function ytmHandler(req) {");
fn = fn.replace(/^export /gm, "");
fn = fn.replace(/\n\};\s*$/, "\n}\n");
if (fn.includes("export ") || fn.includes("default async (req)")) {
  throw new Error("the function's module syntax changed; update build-worker.mjs");
}

const index = await read("public/index.html");
const css = await read("public/style.css");
const app = await read("public/app.js");

const banner = `// Generated by web/build-worker.mjs — do not edit by hand.
// Cloudflare Worker: serves the page and the /api/ytm endpoint with no CLI,
// no Git connection, and no build step. Paste this whole file into the
// dashboard's worker editor, deploy, then set APP_KEY under
// Settings -> Variables and Secrets.
`;

const wrapper = `
const FILES = {
  "/": { body: ${JSON.stringify(index)}, type: "text/html; charset=utf-8" },
  "/index.html": { body: ${JSON.stringify(index)}, type: "text/html; charset=utf-8" },
  "/style.css": { body: ${JSON.stringify(css)}, type: "text/css; charset=utf-8" },
  "/app.js": { body: ${JSON.stringify(app)}, type: "text/javascript; charset=utf-8" },
};

const SECURITY = {
  "x-robots-tag": "noindex, nofollow",
  "x-frame-options": "DENY",
  "referrer-policy": "no-referrer",
  "x-content-type-options": "nosniff",
  "cache-control": "no-store",
};

export default {
  async fetch(request, env) {
    globalThis.__YTM_APP_KEY = typeof env?.APP_KEY === "string" ? env.APP_KEY : "";
    const url = new URL(request.url);
    if (url.pathname === "/api/ytm" || url.pathname === "/.netlify/functions/ytm") {
      return ytmHandler(request);
    }
    const file = FILES[url.pathname];
    if (!file) return new Response("not found", { status: 404 });
    return new Response(file.body, { headers: { "content-type": file.type, ...SECURITY } });
  },
};
`;

const out = banner + "\n" + fn + wrapper;
await mkdir(path.join(here, "dist"), { recursive: true });
await writeFile(path.join(here, "dist", "worker.js"), out);
console.log(`wrote web/dist/worker.js (${out.length} bytes)`);
